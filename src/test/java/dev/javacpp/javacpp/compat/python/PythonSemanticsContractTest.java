import java.math.BigInteger;
import java.nio.charset.StandardCharsets;
import java.util.*;
import java.util.stream.*;
import org.junit.jupiter.api.*;

/**
 * Replays CPython 3.13 builtin-protocol fixtures generated by
 * tools/python_compat/generate_semantics_contracts.py. Every case encodes tagged arguments and the
 * exact expected value or (exception type, str(exc)) pair.
 */
class PythonSemanticsContractTest {
  @TestFactory
  Stream<DynamicTest> cpythonSemantics() throws Exception {
    List<String> lines;
    try (var input =
        Objects.requireNonNull(
            getClass().getResourceAsStream("/python-0.3.36-semantics-contracts.tsv"),
            "Run generate_semantics_contracts.py")) {
      lines = new String(input.readAllBytes(), StandardCharsets.US_ASCII).lines().toList();
    }
    return IntStream.range(0, lines.size())
        .mapToObj(
            i ->
                DynamicTest.dynamicTest(
                    parts(lines.get(i))[0] + ":" + i, () -> run(lines.get(i), i)));
  }

  private static String[] parts(String line) {
    return line.split("\t");
  }

  @SuppressWarnings("unchecked")
  private static void run(String line, int index) throws Exception {
    String[] parts = parts(line);
    Map<String, Object> fixture = (Map<String, Object>) read(parts[1]);
    Object expected = read(parts[2]);
    String op = (String) fixture.get("op");
    List<Object> rawArgs = (List<Object>) fixture.get("args");
    Object[] args = new Object[rawArgs.size()];
    for (int i = 0; i < args.length; i++) args[i] = untag(rawArgs.get(i));
    Object actual;
    try {
      actual = encode(execute(op, args));
    } catch (PythonException error) {
      actual = List.of("err", error.type().pythonName(), error.getMessage());
    } catch (RuntimeException error) {
      actual = List.of("err", "java:" + error.getClass().getSimpleName(), String.valueOf(error.getMessage()));
    }
    assertEquals(expected, actual, "case=" + index + " op=" + op + " args=" + fixture.get("args"));
  }

  private static Object execute(String op, Object[] a) {
    return switch (op) {
      case "truth" -> Py.truth(a[0]);
      case "len" -> Py.len(a[0]);
      case "str" -> Py.str(a[0]);
      case "repr" -> Py.repr(a[0]);
      case "int" -> Py.integer(a[0]);
      case "float" -> Py.floating(a[0]);
      case "index" -> Py.index(a[0]);
      case "iter" -> iterate(a[0]);
      case "neg" -> Py.negate(a[0]);
      case "cint" -> Py.cInt(a[0]);
      case "eq" -> Py.compare(a[0], Py.Op.EQ, a[1]);
      case "ne" -> Py.compare(a[0], Py.Op.NE, a[1]);
      case "lt" -> Py.compare(a[0], Py.Op.LT, a[1]);
      case "le" -> Py.compare(a[0], Py.Op.LE, a[1]);
      case "gt" -> Py.compare(a[0], Py.Op.GT, a[1]);
      case "ge" -> Py.compare(a[0], Py.Op.GE, a[1]);
      case "add" -> Py.add(a[0], a[1]);
      case "sub" -> Py.subtract(a[0], a[1]);
      case "mul" -> Py.multiply(a[0], a[1]);
      case "in" -> Py.contains(a[0], a[1]);
      case "get" -> Py.getItem(a[0], a[1]);
      case "set" -> {
        Py.setItem(a[0], a[1], a[2]);
        yield a[0];
      }
      case "del" -> {
        Py.delItem(a[0], a[1]);
        yield a[0];
      }
      case "slice" -> {
        Py.Slice s = (Py.Slice) a[1];
        yield Py.slice(a[0], s.start(), s.stop(), s.step());
      }
      case "strm" ->
          PythonStrings.apply(
              (String) a[0], a[1], ((List<?>) a[2]).toArray());
      case "utf8" -> PythonBytes.decodeUtf8((byte[]) a[0]);
      case "brepr" -> PythonBytes.repr((byte[]) a[0]);
      case "printable" -> printableRanges();
      case "jdumps" ->
          PythonJson.dumps(
              a[0],
              (Boolean) a[1],
              a[2] == null ? null : ((Number) a[2]).intValue(),
              a[3] == null
                  ? null
                  : ((List<?>) a[3]).stream().map(String.class::cast).toList(),
              (Boolean) a[4]);
      case "jloads" -> PythonJson.loads((String) a[0]);
      default -> throw new AssertionError(op);
    };
  }

  private static List<Object> iterate(Object value) {
    List<Object> items = new ArrayList<>();
    PyIterator iterator = Py.iter(value);
    while (iterator.hasNext()) items.add(iterator.next());
    // CPython set iteration order is hash-dependent; the fixture sorts by repr on both sides.
    if (value instanceof Set) items.sort(Comparator.comparing(Py::repr));
    return items;
  }

  private static List<Object> printableRanges() {
    List<Object> ranges = new ArrayList<>();
    int start = -1;
    for (int cp = 0; cp < 0x110000; cp++) {
      boolean p = PythonUnicode.printable(cp);
      if (p && start < 0) start = cp;
      if (!p && start >= 0) {
        ranges.add(start);
        ranges.add(cp - 1);
        start = -1;
      }
    }
    if (start >= 0) {
      ranges.add(start);
      ranges.add(0x10FFFF);
    }
    return ranges;
  }

  /** Materialize a tagged fixture value into the Java runtime representation. */
  @SuppressWarnings("unchecked")
  private static Object untag(Object tagged) {
    List<Object> fields = (List<Object>) tagged;
    String kind = (String) fields.get(0);
    return switch (kind) {
      case "none" -> null;
      case "bool" -> fields.get(1);
      case "int" -> new BigInteger((String) fields.get(1));
      case "float" -> floatTag((String) fields.get(1));
      case "str" -> fields.get(1);
      case "bytes" -> hex((String) fields.get(1));
      case "list", "tuple", "set", "frozenset" -> {
        List<Object> items = new ArrayList<>();
        for (Object item : (List<Object>) fields.get(1)) items.add(untag(item));
        yield switch (kind) {
          case "list" -> items;
          case "tuple" -> PyTuple.wrap(items);
          case "frozenset" -> new dev.javacpp.python.PyFrozenSet(items);
          default -> pySet(items);
        };
      }
      case "dict" -> {
        Map<Object, Object> map = new LinkedHashMap<>();
        for (Object pair : (List<Object>) fields.get(1)) {
          List<Object> kv = (List<Object>) pair;
          Py.setItem(map, untag(kv.get(0)), untag(kv.get(1)));
        }
        yield map;
      }
      case "slice" -> new Py.Slice(untag(fields.get(1)), untag(fields.get(2)), untag(fields.get(3)));
      case "indexobj" -> new Idx(new BigInteger((String) fields.get(1)));
      case "object" -> new object();
      default -> throw new AssertionError(kind);
    };
  }

  /** Encode a Java-side result into the same tagged shape the generator emits. */
  private static Object encode(Object value) {
    if (value == null) return List.of("none");
    if (value instanceof Boolean b) return List.of("bool", b);
    if (value instanceof String s) return List.of("str", s);
    if (value instanceof BigInteger
        || value instanceof Byte
        || value instanceof Short
        || value instanceof Integer
        || value instanceof Long)
      return List.of("int", value.toString());
    if (value instanceof Number n) return List.of("float", floatTag(n.doubleValue()));
    if (value instanceof byte[] b) return List.of("bytes", hex(b));
    if (value instanceof PyTuple<?> t) return List.of("tuple", encodeList(t));
    if (value instanceof List<?> l) return List.of("list", encodeList(l));
    if (value instanceof Map<?, ?> m) {
      List<Object> pairs = new ArrayList<>();
      for (var entry : m.entrySet())
        pairs.add(List.of(encode(entry.getKey()), encode(entry.getValue())));
      return List.of("dict", pairs);
    }
    if (value instanceof dev.javacpp.python.PyFrozenSet s)
      return List.of("frozenset", encodeList(new ArrayList<>(s)));
    if (value instanceof Set<?> s) return List.of("set", encodeList(new ArrayList<>(s)));
    if (value instanceof Py.Slice s)
      return List.of("slice", encode(s.start()), encode(s.stop()), encode(s.step()));
    if (value instanceof Idx i) return List.of("indexobj", i.index.toString());
    return List.of("java", value.getClass().getName());
  }

  /** Build a mutable set preserving Python equality-merged insertion order. */
  private static Set<Object> pySet(List<Object> items) {
    LinkedHashSet<Object> set = new LinkedHashSet<>();
    outer:
    for (Object item : items) {
      for (Object stored : set) if (Py.equal(stored, item)) continue outer;
      set.add(item);
    }
    return set;
  }

  private static List<Object> encodeList(List<?> items) {
    List<Object> out = new ArrayList<>(items.size());
    for (Object item : items) out.add(encode(item));
    return out;
  }

  private static Object floatTag(String bits) {
    return switch (bits) {
      case "nan" -> Double.NaN;
      case "inf" -> Double.POSITIVE_INFINITY;
      case "-inf" -> Double.NEGATIVE_INFINITY;
      default -> Double.longBitsToDouble(new BigInteger(bits, 16).longValue());
    };
  }

  private static String floatTag(double value) {
    if (Double.isNaN(value)) return "nan";
    if (value == Double.POSITIVE_INFINITY) return "inf";
    if (value == Double.NEGATIVE_INFINITY) return "-inf";
    return String.format("%016x", Double.doubleToRawLongBits(value));
  }

  private static byte[] hex(String text) {
    byte[] out = new byte[text.length() / 2];
    for (int i = 0; i < out.length; i++)
      out[i] = (byte) Integer.parseInt(text.substring(2 * i, 2 * i + 2), 16);
    return out;
  }

  private static String hex(byte[] bytes) {
    StringBuilder out = new StringBuilder(bytes.length * 2);
    for (byte b : bytes) out.append(String.format("%02x", Byte.toUnsignedInt(b)));
    return out.toString();
  }

  private static Object read(String value) throws Exception {
    return PythonContractData.read(
        new DataInputStream(new ByteArrayInputStream(Base64.getDecoder().decode(value))));
  }

  /** Python object stand-in so typeName reports "object". */
  static class object {}

  /** __index__-carrying object whose repr mirrors CPython's normalized "object at 0x0" wording. */
  static class Idx implements PyIndexed {
    final BigInteger index;

    Idx(BigInteger index) {
      this.index = index;
    }

    @Override
    public BigInteger pyIndex() {
      return index;
    }

    @Override
    public String toString() {
      return "<__main__.Idx object at 0x0>";
    }
  }
}
